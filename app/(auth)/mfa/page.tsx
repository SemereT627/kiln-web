"use client";

import { useEffect, useState } from "react";
import { createClient } from "@/lib/supabase/client";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { AuthShell } from "@/components/auth-shell";
import { AlertCircle, Loader2 } from "lucide-react";

type Mode =
  | { kind: "loading" }
  | { kind: "enroll"; factorId: string; qrCode: string; secret: string }
  | { kind: "verify"; factorId: string }
  | { kind: "error"; message: string };

/**
 * Second sign-in step for the web dashboard. The proxy sends every session
 * below aal2 here. First visit: scan a QR code into an authenticator app and
 * confirm a code (enrol). Later visits: just enter the current code.
 */
export default function MfaPage() {
  const [mode, setMode] = useState<Mode>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);

  useEffect(() => {
    const supabase = createClient();
    (async () => {
      const { data, error } = await supabase.auth.mfa.listFactors();
      if (error) {
        setMode({ kind: "error", message: error.message });
        return;
      }
      const verified = data.totp.find((f) => f.status === "verified");
      if (verified) {
        setMode({ kind: "verify", factorId: verified.id });
        return;
      }
      // Clear any half-finished enrolment (QR shown but never confirmed)
      // so a fresh one can be created.
      for (const f of data.all.filter((f) => f.status === "unverified")) {
        await supabase.auth.mfa.unenroll({ factorId: f.id });
      }
      const { data: enrolled, error: enrollError } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: "Kiln",
        issuer: "Kiln",
      });
      if (enrollError || !enrolled) {
        setMode({ kind: "error", message: enrollError?.message ?? "Couldn't start setup." });
        return;
      }
      setMode({
        kind: "enroll",
        factorId: enrolled.id,
        qrCode: enrolled.totp.qr_code,
        secret: enrolled.totp.secret,
      });
    })();
  }, []);

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (mode.kind !== "enroll" && mode.kind !== "verify") return;
    setSubmitting(true);
    setError(null);
    const supabase = createClient();
    const { error } = await supabase.auth.mfa.challengeAndVerify({
      factorId: mode.factorId,
      code: code.trim(),
    });
    if (error) {
      setError("That code didn't work. Check your authenticator app and try again.");
      setCode("");
      setSubmitting(false);
      return;
    }
    // Full load so the proxy sees the upgraded (aal2) session cookie.
    window.location.assign("/en/dashboard");
  }

  async function handleSignOut() {
    await createClient().auth.signOut();
    window.location.assign("/login");
  }

  return (
    <AuthShell>
      <div className="space-y-2">
        <h2 className="font-display text-3xl font-medium tracking-[-0.015em]">
          {mode.kind === "enroll" ? "Set up two-step sign-in" : "Enter your code"}
        </h2>
        <p className="text-muted-foreground text-sm">
          {mode.kind === "enroll"
            ? "Scan this QR code with an authenticator app (Google Authenticator, Microsoft Authenticator, 1Password), then enter the 6-digit code it shows."
            : "Open your authenticator app and enter the 6-digit code for Kiln."}
        </p>
      </div>

      {mode.kind === "loading" && (
        <div className="flex justify-center py-10">
          <Loader2 className="size-6 animate-spin text-muted-foreground" aria-label="Loading" />
        </div>
      )}

      {mode.kind === "error" && (
        <div className="flex items-start gap-2 rounded-lg border border-destructive/15 bg-destructive/8 px-3 py-2.5 text-sm text-destructive">
          <AlertCircle className="mt-0.5 size-4 shrink-0" />
          <span>{mode.message}</span>
        </div>
      )}

      {mode.kind === "enroll" && (
        <div className="space-y-3">
          {/* QR code is an SVG data URL generated by Supabase, not a product image */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={mode.qrCode}
            alt="QR code for your authenticator app"
            className="mx-auto size-44 rounded-lg bg-white p-2"
          />
          <div className="text-center text-xs text-muted-foreground">
            Can&apos;t scan? Enter this key instead:
            <p className="mt-1 font-mono text-sm tracking-wider text-foreground break-all select-all">
              {mode.secret}
            </p>
          </div>
        </div>
      )}

      {(mode.kind === "enroll" || mode.kind === "verify") && (
        <form onSubmit={handleSubmit} className="space-y-5">
          <div className="space-y-2">
            <Label htmlFor="code" className="text-sm font-medium">
              6-digit code
            </Label>
            <Input
              id="code"
              inputMode="numeric"
              autoComplete="one-time-code"
              pattern="[0-9]{6}"
              maxLength={6}
              placeholder="123456"
              value={code}
              onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
              autoFocus
              required
              className="h-11 text-center font-mono text-lg tracking-[0.4em]"
            />
          </div>

          {error && (
            <div className="flex items-start gap-2 rounded-lg border border-destructive/15 bg-destructive/8 px-3 py-2.5 text-sm text-destructive">
              <AlertCircle className="mt-0.5 size-4 shrink-0" />
              <span>{error}</span>
            </div>
          )}

          <Button
            type="submit"
            size="lg"
            className="w-full"
            disabled={submitting || code.length !== 6}
            aria-busy={submitting}
          >
            {submitting ? (
              <>
                <Loader2 className="size-5 animate-spin" aria-hidden="true" />
                <span className="sr-only">Verifying</span>
              </>
            ) : mode.kind === "enroll" ? (
              "Turn on and continue"
            ) : (
              "Verify"
            )}
          </Button>
        </form>
      )}

      <p className="text-center text-sm text-muted-foreground">
        {mode.kind === "verify" && "Lost your phone? Ask an administrator to reset your two-step sign-in. "}
        <button
          type="button"
          onClick={handleSignOut}
          className="font-semibold text-foreground underline-offset-4 hover:underline"
        >
          Sign out
        </button>
      </p>
    </AuthShell>
  );
}
